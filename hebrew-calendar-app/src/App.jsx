function numToHebrew(n) {
  if (n <= 0) return "";
  const thousands = Math.floor(n / 1000);
  n = n % 1000;
  const hundreds = Math.floor(n / 100);
  n = n % 100;
  // Special cases
  if (n === 15) return (thousands ? HEBREW_THOUSANDS[thousands] + "׳" : "") + HEBREW_HUNDREDS[hundreds] + "טו";
  if (n === 16) return (thousands ? HEBREW_THOUSANDS[thousands] + "׳" : "") + HEBREW_HUNDREDS[hundreds] + "טז";
  const tens = Math.floor(n / 10);
  const units = n % 10;
  let result = "";
  if (thousands) result += HEBREW_THOUSANDS[thousands] + "׳";
  result += HEBREW_HUNDREDS[hundreds] + HEBREW_TENS[tens] + HEBREW_UNITS[units];
  return result;
}

function yearToHebrew(year) {
  // year is Hebrew year
  const thousands = Math.floor(year / 1000);
  const rest = year % 1000;
  const h = Math.floor(rest / 100);
  const t = Math.floor((rest % 100) / 10);
  const u = rest % 10;
  let s = HEBREW_HUNDREDS[h] + HEBREW_TENS[t] + HEBREW_UNITS[u];
  if (s.length > 1) {
    s = s.slice(0, -1) + '״' + s.slice(-1);
  } else {
    s = s + '׳';
  }
  return 'ה׳' + s;
}

// Rata Die for Hebrew dates using the standard algorithm
function hebrewToJD(year, month, day) {
  // Using the Meeus algorithm
  const EPOCH = 347995.5; // Julian Day of Hebrew epoch
  let months;
  if (isHebrewLeapYear(year)) {
    months = [0,30,29,29,29,30,30,29,30,29,30,29,30,29];
  } else {
    months = [0,30,29,29,29,30,29,30,29,30,29,30,29];
  }
  // Adjust month lengths for chesvan/kislev
  months[2] = hebrewMonthDays(year, 2);
  months[3] = hebrewMonthDays(year, 3);

  let jd = hebrewYearStart(year);
  for (let m = 1; m < month; m++) {
    jd += hebrewMonthDays(year, m);
  }
  jd += day - 1;
  return jd;
}

function isHebrewLeapYear(year) {
  return ((7 * year + 1) % 19) < 7;
}

function hebrewYearMonths(year) {
  return isHebrewLeapYear(year) ? 13 : 12;
}

function hebrewDelay1(year) {
  const months = Math.floor((235 * year - 234) / 19);
  const parts = 12084 + 13753 * months;
  let day = months * 29 + Math.floor(parts / 25920);
  if (((3 * (day + 1)) % 7) < 3) day++;
  return day;
}

function hebrewDelay2(year) {
  const last = hebrewDelay1(year - 1);
  const present = hebrewDelay1(year);
  const next = hebrewDelay1(year + 1);
  if ((next - present) === 356) return 2;
  if ((present - last) === 382) return 1;
  return 0;
}

function hebrewYearStart(year) {
  // Returns absolute day count from Hebrew epoch
  const delay = hebrewDelay1(year) + hebrewDelay2(year);
  return delay + 1;
}

function hebrewYearDays(year) {
  return hebrewYearStart(year + 1) - hebrewYearStart(year);
}

function hebrewMonthDays(year, month) {
  // month: 1=Tishri, ...
  const leap = isHebrewLeapYear(year);
  // Long months: 1,3,5,7,11
  // Short months: 4,6,8,10,12,13(leap)
  // Variable: 2(Cheshvan), 3(Kislev)
  const longMonths = [1,3,5,7,11];
  if (leap) longMonths.push(6); // Adar I in leap year has 30 days? Actually 30
  const shortMonths = [4,6,8,10,12];
  if (leap) { shortMonths.push(13); }

  if (month === 2) {
    // Cheshvan: 29 or 30
    const yd = hebrewYearDays(year);
    return (yd % 10 === 5) ? 30 : 29;
  }
  if (month === 3) {
    // Kislev: 29 or 30
    const yd = hebrewYearDays(year);
    return (yd % 10 === 3) ? 29 : 30;
  }
  // Adar in non-leap: 29; Adar I in leap: 30; Adar II: 29
  if (!leap && month === 6) return 29;
  if (leap && month === 6) return 30;
  if (leap && month === 7) return 29;

  const odd = [1,3,5,7,9,11];
  // 1,3,5,7 = 30; 4,6,8,10,12 = 29; 9=Sivan=30; 11=Av=30
  const thirtyDayMonths = [1, 3, 5, 7, 9, 11];
  return thirtyDayMonths.includes(month) ? 30 : 29;
}

// Convert Gregorian to absolute day
function gregorianToAbsolute(year, month, day) {
  const y = year - 1;
  return (
    day +
    [0,31,59,90,120,151,181,212,243,273,304,334][month - 1] +
    (month > 2 && isGregorianLeap(year) ? 1 : 0) +
    365 * y +
    Math.floor(y / 4) -
    Math.floor(y / 100) +
    Math.floor(y / 400)
  );
}

function isGregorianLeap(year) {
  return (year % 4 === 0 && year % 100 !== 0) || year % 400 === 0;
}

// Hebrew absolute day starts from Hebrew epoch
// Hebrew epoch in absolute Gregorian days = Oct 7, 3761 BCE
const HEBREW_EPOCH = -1373427; // absolute day of Hebrew epoch (Tishri 1, year 1)

function absoluteToHebrew(abs) {
  // Estimate Hebrew year
  let year = Math.floor((abs + 1373427) / 365.25 * (235/19)) + 1;
  // Adjust
  while (hebrewYearStart(year + 1) <= abs - HEBREW_EPOCH + 1) year++;
  while (hebrewYearStart(year) > abs - HEBREW_EPOCH + 1) year--;

  const dayInYear = abs - HEBREW_EPOCH + 1 - hebrewYearStart(year) + 1;
  let month = 1;
  const numMonths = hebrewYearMonths(year);
  let daysAcc = 0;
  for (let m = 1; m <= numMonths; m++) {
    const md = hebrewMonthDays(year, m);
    if (daysAcc + md >= dayInYear) { month = m; break; }
    daysAcc += md;
  }
  const day = dayInYear - daysAcc;
  return { year, month, day };
}

function gregorianToHebrew(gYear, gMonth, gDay) {
  const abs = gregorianToAbsolute(gYear, gMonth, gDay);
  return absoluteToHebrew(abs);
}

