// ─── Hebrew → Gregorian conversion ───────────────────────────────────────────

function hebrewToGregorian(hYear, hMonth, hDay) {
  // Get absolute day from Hebrew date
  const absDay = HEBREW_EPOCH + hebrewYearStart(hYear) - 1 + (() => {
    let acc = 0;
    for (let m = 1; m < hMonth; m++) acc += hebrewMonthDays(hYear, m);
    return acc;
  })() + hDay - 1;

  // Convert absolute day to Gregorian
  // abs=1 is Jan 1, year 1
  let year = Math.floor(absDay / 365.2425);
  while (gregorianToAbsolute(year + 1, 1, 1) <= absDay) year++;
  while (gregorianToAbsolute(year, 1, 1) > absDay) year--;

  let month = 1;
  while (month < 12 && gregorianToAbsolute(year, month + 1, 1) <= absDay) month++;

  const day = absDay - gregorianToAbsolute(year, month, 1) + 1;
  return { year, month, day };
}

// Bar/Bat Mitzvah: 13 Hebrew years after birth for boys, 12 for girls
// Returns the Hebrew date + Gregorian equivalent
function calcBarMitzvah(hYear, hMonth, hDay, gender) {
  const yearsToAdd = gender === "f" ? 12 : 13;
  let bmYear = hYear + yearsToAdd;
  let bmMonth = hMonth;
  let bmDay = hDay;

  // Handle case where birth month doesn't exist in bar/bat mitzvah year
  // e.g. born Adar in non-leap, BM year is leap → Adar II (month 7)
  // born Adar in leap (Adar I=6 or Adar II=7), BM year is non-leap → Adar (month 6)
  const birthLeap = isHebrewLeapYear(hYear);
  const bmLeap = isHebrewLeapYear(bmYear);

  if (birthLeap && !bmLeap) {
    if (hMonth === 6) bmMonth = 6;       // Adar I → Adar
    if (hMonth === 7) bmMonth = 6;       // Adar II → Adar
  }
  if (!birthLeap && bmLeap) {
    if (hMonth === 6) bmMonth = 7;       // Adar → Adar II (standard halachic ruling)
  }

  // Clamp day if month is shorter in BM year
  const maxDay = hebrewMonthDays(bmYear, bmMonth);
  if (bmDay > maxDay) bmDay = maxDay;

  const greg = hebrewToGregorian(bmYear, bmMonth, bmDay);
  return { hYear: bmYear, hMonth: bmMonth, hDay: bmDay, greg };
}

